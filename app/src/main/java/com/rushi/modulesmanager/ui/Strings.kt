fun stringsFor(option: AppLanguageOption): AppStrings {
    val isRu = when (option) {
        AppLanguageOption.RUSSIAN -> true
        AppLanguageOption.ENGLISH -> false
        AppLanguageOption.SYSTEM -> Locale.getDefault().language.equals("ru", ignoreCase = true)
    }
    return if (isRu) RussianStrings else EnglishStrings
}

val LocalStrings = staticCompositionLocalOf { EnglishStrings }
